const DICTS: Record<Lang, Dict> = { es: {}, en, pt, fr };

let current: Lang = "es";
export const setLang = (l: Lang) => {
  current = l;
};
export const getLang = () => current;

/** Traduce `key` (texto en español) al idioma activo y sustituye `{var}`. */
export function t(key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[current][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export const LangContext = createContext<Lang>("es");

/** `t` que fuerza el rerender al cambiar el idioma (el contexto solo sirve como señal). */
export function useT() {
  useContext(LangContext);
  return t;
}
